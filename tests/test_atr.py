from src.indicators.atr import ATR


def test_atr():

    highs = [
        48.70, 48.72, 48.90, 48.87, 48.82,
        49.05, 49.20, 49.35, 49.40, 49.50,
        49.60, 49.75, 49.80, 49.90, 50.00
    ]

    lows = [
        47.79, 48.14, 48.39, 48.37, 48.24,
        48.64, 48.94, 48.86, 49.03, 49.20,
        49.30, 49.40, 49.55, 49.60, 49.75
    ]

    closes = [
        48.16, 48.61, 48.75, 48.63, 48.74,
        49.03, 49.07, 49.32, 49.37, 49.45,
        49.55, 49.70, 49.76, 49.88, 49.95
    ]

    atr = ATR()

    value = atr.calculate(highs, lows, closes)

    assert value is not None
    assert value > 0